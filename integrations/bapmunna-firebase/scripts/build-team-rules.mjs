// 호환판 로컬 에뮬레이터가 사용할 규칙을 생성한다. 팀 운영 규칙은 apps/warming-up/firebase/firestore.rules에 있다.
// 사용: node scripts/build-team-rules.mjs [--check]
import {readFile, writeFile, mkdir} from 'node:fs/promises';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const check = process.argv.includes('--check');
const fragments = await Promise.all(['bapmunna.rules', 'care-domain.rules']
  .map(name => readFile(path.join(root, 'firebase', name), 'utf8').then(s => s.replace(/\r\n/g, '\n').replace(/\n+$/, ''))));
const rules = `// GENERATED by scripts/build-team-rules.mjs from firebase/bapmunna.rules + firebase/care-domain.rules. Do not edit.
rules_version = '2';
service cloud.firestore {
  match /databases/{database}/documents {
${fragments.join('\n')}
    // Everything outside the Bapmunna namespaces is closed.
    match /{document=**} { allow read, write: if false; }
  }
}
`;
const target = path.join(root, 'firebase/team-firestore.rules');
if (check) {
  const actual = (await readFile(target, 'utf8').catch(() => null))?.replace(/\r\n/g, '\n');
  if (actual !== rules) { console.error('Out of date: firebase/team-firestore.rules. Run node scripts/build-team-rules.mjs'); process.exitCode = 1; }
  else console.log('Team Firestore rules are up to date.');
} else {
  await writeFile(target, rules);
  // The emulator suite (npm run test:cloud) reads tmp/firebase/merged.rules.
  await mkdir(path.join(root, 'tmp/firebase'), {recursive: true});
  await writeFile(path.join(root, 'tmp/firebase/merged.rules'), rules);
  console.log('Built firebase/team-firestore.rules and tmp/firebase/merged.rules.');
}
