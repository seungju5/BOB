// Keep the archived local UI's share links aligned with the team web app.
import {readFile, writeFile} from 'node:fs/promises';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const app = path.join(root, 'integrations/bapmunna-firebase');
const check = process.argv.includes('--check');
const readJson = async file => JSON.parse(await readFile(path.join(root, file), 'utf8'));
const {webOrigin, privacySupportEmail} = await readJson('config/deployment.json');
const {projects} = await readJson('apps/warming-up/.firebaserc');
if (webOrigin !== `https://${projects.default}.web.app`) throw Error('Use the team Hosting origin in config/deployment.json.');
if (!/^[^@\s]+@[^@\s]+\.[^@\s]+$/.test(privacySupportEmail)) throw Error('Invalid team support email.');

const generated = '// Generated by scripts/apply-deployment.mjs.\n';
const deployment = `${generated}export const deploymentConfig=Object.freeze(${JSON.stringify({webOrigin})});\n`;
const outputs = {
  'docs/deployment-config.mjs': deployment,
  'cloud/deployment-config.mjs': deployment,
  'docs/smartthings-config.mjs': `${generated}export const smartThingsApiOrigin="";\n`,
  'cloud/kakao-config.mjs': `${generated}export const kakaoConfig=Object.freeze({enabled:false});\n`,
};
const shell = 'docs/index.html';
const html = await readFile(path.join(app, shell), 'utf8');
outputs[shell] = html.replace(/\r\n/g, '\n')
  .replace(/(<link rel="canonical" href="|<meta property="og:url" content=")[^"]+/g, `$1${webOrigin}/`)
  .replace(/(<meta (?:property|name)="(?:og:image(?::secure_url)?|twitter:image)" content=")[^"]+/g, `$1${webOrigin}/brand/bapmunna-share-v2.png`);

for (const [file, content] of Object.entries(outputs)) {
  const target = path.join(app, file);
  if (check) {
    const actual = await readFile(target, 'utf8').catch(() => '');
    if (actual.replace(/\r\n/g, '\n') !== content) throw Error(`Run npm run apply:deployment to update ${file}.`);
  } else {
    await writeFile(target, content);
  }
}
console.log(`Team sharing links ${check ? 'verified' : 'updated'} for ${webOrigin}.`);
