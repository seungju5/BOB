// config/deployment.json(팀 배포 대상)을 Firebase 정적 앱의 공개 설정 파일로 옮겨 쓴다.
// 사용: npm run apply:deployment          (파일 생성)
//       npm run check:deployment          (생성본이 최신인지 검사, 빌드 전에 실행)
import {readFile, writeFile} from 'node:fs/promises';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const app = path.join(root, 'integrations/bapmunna-firebase');
const check = process.argv.includes('--check');
const d = JSON.parse(await readFile(path.join(root, 'config/deployment.json'), 'utf8'));

const origin = (name, value) => {
  const url = new URL(value);
  if (url.protocol !== 'https:' || url.origin !== value) throw Error(`${name} must be an https origin without a path: ${value}`);
  return url.origin;
};
const webOrigin = origin('webOrigin', d.webOrigin);
const apiOrigin = origin('apiOrigin', d.apiOrigin);
for (const key of ['apiKey', 'authDomain', 'projectId', 'appId']) {
  if (typeof d.firebase?.[key] !== 'string' || !d.firebase[key]) throw Error(`firebase.${key} is required`);
}
if (!/^[^@\s]+@[^@\s]+\.[^@\s]+$/.test(d.privacySupportEmail)) throw Error('privacySupportEmail is invalid');

const generated = '// GENERATED by scripts/apply-deployment.mjs from config/deployment.json. Do not edit.\n';
const firebaseConfig = {apiKey: d.firebase.apiKey, authDomain: d.firebase.authDomain, projectId: d.firebase.projectId, appId: d.firebase.appId};
const deploymentConfig = `${generated}export const deploymentConfig=Object.freeze(${JSON.stringify({webOrigin, apiOrigin, firebaseProjectId: d.firebase.projectId})});\n`;
const outputs = {
  'docs/firebase-config.mjs': `${generated}// Public browser SDK configuration only.\nexport const firebaseConfig=${JSON.stringify(firebaseConfig, null, 2)};\n`,
  'docs/smartthings-config.mjs': `${generated}// New connections remain independently gated by config.connectionReady on the server.\nexport const smartThingsApiOrigin=${JSON.stringify(apiOrigin)};\n`,
  'docs/deployment-config.mjs': deploymentConfig,
  'cloud/deployment-config.mjs': deploymentConfig,
  'cloud/kakao-config.mjs': `${generated}// Public capability, never an OAuth key. The server must also report ready.\nexport const kakaoConfig=Object.freeze({enabled:true,apiOrigin:${JSON.stringify(apiOrigin)}});\n`,
};

// Share/canonical meta tags in the static shell carry the public origin.
const shellPath = 'docs/index.html';
const shell = (await readFile(path.join(app, shellPath), 'utf8')).replace(/\r\n/g, '\n');
outputs[shellPath] = shell.replace(/(<(?:link rel="canonical" href|meta (?:property|name)="(?:og:url|og:image|og:image:secure_url|twitter:image)" content)=")https:\/\/[^/"]+(\/bapmunna)/g, `$1${webOrigin}$2`);

let stale = false;
for (const [file, content] of Object.entries(outputs)) {
  const target = path.join(app, file);
  if (check) {
    const actual = (await readFile(target, 'utf8').catch(() => null))?.replace(/\r\n/g, '\n');
    if (actual !== content) { console.error('Out of date:', path.relative(root, target)); stale = true; }
  } else await writeFile(target, content);
}
if (stale) { console.error('Run `npm run apply:deployment`, then `npm run build:firebase`.'); process.exitCode = 1; }
else console.log(check ? 'Deployment config matches config/deployment.json.' : `Applied deployment config (${d.firebase.projectId}, ${webOrigin}).`);
