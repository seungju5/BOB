// Firebase's approved visual assets are also the Next.js and design handoff source.
import {readFile, writeFile, mkdir} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import path from 'node:path';
const root=path.resolve(import.meta.dirname,'..');
const source=path.join(root,'integrations/bapmunna-firebase/docs');
const check=process.argv.includes('--check');
const sha=data=>createHash('sha256').update(data).digest('hex');
async function output(name,data){
  const target=path.join(root,name);
  // Text outputs ignore CRLF vs LF so a Windows checkout is not reported as design drift.
  if(check){
    const same=typeof data==='string'
      ?(await readFile(target,'utf8')).replace(/\r\n/g,'\n')===data
      :Buffer.from(await readFile(target)).equals(Buffer.from(data));
    if(!same)throw Error('Design drift: '+name);
  }
  else {await mkdir(path.dirname(target),{recursive:true});await writeFile(target,data);}
}
const assets={};
for(const name of ['bunny.png','bunny-underlay.webp','bunny-greeting.webp','rice-logo.png','rice-cooker-companion.png','bapmunna-share-v2.png','PretendardVariable.woff2','NanumPenScript-Regular.ttf','OFL-Pretendard.txt','OFL-NanumPenScript.txt']){
  const raw=await readFile(path.join(source,'assets',name));
  // License .txt files are text: hash and compare them with LF endings on every OS.
  const data=name.endsWith('.txt')?raw.toString('utf8').replace(/\r\n/g,'\n'):raw;
  assets[name]=sha(data);await output('public/brand/'+name,data);
}
const brand=await readFile(path.join(source,'brand.css'),'utf8');
const tokens=Object.fromEntries([...brand.matchAll(/--([\w-]+):(#[\da-f]{6})(?=;)/gi)].map(m=>[m[1],m[2]]));
const map={cream:'canvas',paper:'paper',butter:'yellow','butter-soft':'soft',cocoa:'ink',ink:'ink',muted:'muted',line:'line',blush:'red-soft','blush-deep':'red',sage:'green-soft','sage-deep':'green'};
await output('app/brand.generated.css',`/* Generated by scripts/sync-design.mjs. Edit the approved Firebase brand source. */\n@font-face{font-family:Pretendard;src:url('../public/brand/PretendardVariable.woff2') format('woff2');font-weight:100 900;font-display:swap}\n@font-face{font-family:NanumPen;src:url('../public/brand/NanumPenScript-Regular.ttf') format('truetype');font-weight:400;font-display:swap}\n@theme{\n${Object.entries(map).map(([key,value])=>`  --color-${key}: ${tokens[value]};`).join('\n')}\n  --font-sans: Pretendard, -apple-system, BlinkMacSystemFont, 'Apple SD Gothic Neo', sans-serif;\n  --font-hand: NanumPen, Pretendard, sans-serif;\n}\n`);
await output('design/2026-11-03-bapmunna/design-manifest.json',JSON.stringify({version:'2026-11-03',source:'integrations/bapmunna-firebase/docs/brand.css',figma:'https://www.figma.com/design/9Io11mLh2rLORVmeyQdg57/?node-id=3317-189',tokens,assets,identity:{welcomeMascot:'bunny.png',mascot:'rice-cooker-companion.png',symbol:'rice-logo.png',share:'bapmunna-share-v2.png'},navigation:['홈','기록','더보기'],seniorActions:['외식했어요','놀러가요','도와줘요'],api:'Presentation only; authentication, consent and API contracts remain independent.'},null,2)+'\n');
console.log(check?'Approved design assets and tokens match.':'Synced approved design assets and tokens.');
