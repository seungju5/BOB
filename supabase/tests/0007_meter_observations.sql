-- Synthetic regression for the migrated team DB. The test transaction always rolls back.
begin;
do $test$
declare
  h uuid; guardian uuid := gen_random_uuid(); outsider uuid := gen_random_uuid(); plug uuid;
  outlet text := 'synthetic-cooker'; start_at timestamptz := now() - interval '55 minutes';
  stored record; n integer; original_secret uuid;
begin
  insert into auth.users(id) values(guardian),(outsider);
  insert into public.households(senior_consent_at) values(start_at - interval '3 hours') returning id into h;
  insert into public.household_guardians(household_id,user_id) values(h,guardian);
  assert not public.record_plug_observation(h,outlet,'recognized',700,start_at,true,10,2,null,'test',outsider);
  assert public.record_plug_observation(h,outlet,'recognized',699,start_at,false,10,2,null,'synthetic',guardian);
  select id, st_token_secret_id into plug, original_secret from public.smart_plugs where household_id=h;
  assert not exists(select 1 from public.cooker_events where household_id=h);
  perform set_config('request.jwt.claim.sub', guardian::text, true);
  perform public.set_plug_power_notice(outlet, true);
  assert public.record_plug_observation(h,outlet,'recognized',700,start_at+interval '1 minute',true,10,2,plug);
  assert public.record_plug_observation(h,outlet,'recognized',5,start_at+interval '6 minutes',false,10,2,plug);
  assert public.record_plug_observation(h,outlet,'recognized',705,start_at+interval '11 minutes',true,10,2,plug);
  assert public.record_plug_observation(h,outlet,'recognized',700,start_at+interval '21 minutes',true,10,2,plug);
  select count(*),min(started_at),max(ended_at) into stored from public.cooker_events where household_id=h;
  assert stored.count=1 and stored.min=start_at+interval '1 minute' and stored.max=start_at+interval '21 minutes';
  assert (select last_power_notice_at from public.smart_plugs where id=plug)=start_at+interval '1 minute';
  assert public.record_plug_observation(h,outlet,'recognized',700,start_at+interval '31 minutes 1 second',true,10,2,plug);
  assert public.record_plug_observation(h,outlet,'recognized',700,start_at+interval '31 minutes 1 second',true,10,2,plug);
  assert public.record_plug_observation(h,outlet,'recognized',700,start_at+interval '1 minute',true,10,2,plug);
  assert (select count(*) from public.cooker_events where household_id=h)=2;
  assert (select count(*) from public.power_readings_raw where plug_id=plug)=6;
  assert (select last_reading_at from public.smart_plugs where id=plug)=start_at+interval '31 minutes 1 second';
  assert (select last_power_notice_at from public.smart_plugs where id=plug)=start_at+interval '31 minutes 1 second';
  perform public.set_plug_power_notice(outlet, false);
  assert (select last_power_notice_at is null from public.smart_plugs where id=plug);
  assert public.record_plug_observation(h,outlet,'recognized',700,start_at+interval '31 minutes 1 second',true,10,2,null,'renewed-test',guardian);
  assert (select st_token_secret_id from public.smart_plugs where id=plug)=original_secret;
  assert (select count(*) from public.cooker_events where household_id=h)=2;
  perform public.save_meter_day_summary(h,current_date,'[{"slot":"breakfast","status":"confirmed","source":"cooker","meter_observed":true}]',2,0);
  perform public.save_meter_day_summary(h,current_date,'[{"slot":"breakfast","status":"unconfirmed","source":null,"meter_observed":true}]',0,0);
  assert (select cook_count from public.daily_cooker_stats where household_id=h and date=current_date)=2;
  assert (select status from public.meal_slots where household_id=h and date=current_date and slot='breakfast')='confirmed';
  insert into public.meal_slots(household_id,date,slot,status,source) values(h,current_date,'dinner','confirmed','senior_check');
  perform public.save_meter_day_summary(h,current_date,'[{"slot":"dinner","status":"unconfirmed","source":null,"meter_observed":true}]',null,null);
  assert (select source from public.meal_slots where household_id=h and date=current_date and slot='dinner')='senior_check';
  assert public.record_plug_observation(h,'synthetic-virtual','virtual',800,now(),true,10,2,null,'virtual-test',guardian);
  assert not public.record_plug_observation(h,outlet,'recognized',900,now(),true,10,2,plug);
  assert (select count(*) from public.cooker_events where household_id=h)=2;
  assert (select last_signal_high is null and observing_since is null and not power_notice_enabled from public.smart_plugs where id=plug);
  perform set_config('request.jwt.claim.sub', outsider::text, true);
  begin
    perform public.disconnect_meter_plug('synthetic-virtual', h);
    raise exception 'outsider unexpectedly disconnected a plug';
  exception when insufficient_privilege then null; end;
  perform set_config('request.jwt.claim.sub', guardian::text, true);
  assert not public.disconnect_meter_plug('already-replaced-device', h);
  assert public.disconnect_meter_plug('synthetic-virtual', h);
  assert not exists(select 1 from vault.secrets where id=original_secret);
  assert (select cook_count from public.daily_cooker_stats where household_id=h and date=current_date)=2;
  assert public.record_plug_observation(h,outlet,'recognized',900,now()-interval '2 hours 1 minute',true,10,2,null,'stale-test',guardian);
  select id, st_token_secret_id into plug, original_secret from public.smart_plugs where household_id=h;
  assert (select status='offline' and observing_since is null from public.smart_plugs where id=plug);
  assert not exists(select 1 from public.power_readings_raw where plug_id=plug);
  update public.households set senior_consent_at=null where id=h;
  assert not public.record_plug_observation(h,'synthetic-virtual','virtual',800,now(),true,10,2,plug);
  assert not exists(select 1 from public.smart_plugs where id=plug);
  assert not exists(select 1 from vault.secrets where id=original_secret);
  assert not has_function_privilege('authenticated','public.record_plug_observation(uuid,text,text,numeric,timestamptz,boolean,integer,integer,uuid,text,uuid)','execute');
  assert has_function_privilege('service_role','public.record_plug_observation(uuid,text,text,numeric,timestamptz,boolean,integer,integer,uuid,text,uuid)','execute');
  assert not has_function_privilege('anon','public.set_plug_power_notice(text,boolean,uuid)','execute');
  assert (select schedule from cron.job where jobname='bapmutna-ingest')='*/10 * * * *';
end;
$test$;
rollback;
